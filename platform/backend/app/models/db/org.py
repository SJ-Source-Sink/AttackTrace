"""
Organization and Workspace database models.
"""

import enum
from datetime import datetime
from typing import Optional
from uuid import uuid4, UUID

from sqlalchemy import (
    Boolean,
    DateTime,
    Enum,
    ForeignKey,
    String,
    Text,
    func,
)
from sqlalchemy.dialects.postgresql import ARRAY, UUID as PGUUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.db.base import Base, TimestampMixin, UUIDPrimaryKeyMixin


class OrgPlan(str, enum.Enum):
    STARTER = "starter"
    PRO = "pro"
    ENTERPRISE = "enterprise"


class Organization(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """Tenant organization."""

    __tablename__ = "organizations"

    name: Mapped[str] = mapped_column(String(255), nullable=False)
    slug: Mapped[str] = mapped_column(String(100), unique=True, nullable=False, index=True)
    plan: Mapped[OrgPlan] = mapped_column(
        Enum(OrgPlan, name="org_plan"), default=OrgPlan.STARTER, nullable=False
    )
    is_active: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)
    max_scans_per_month: Mapped[int] = mapped_column(default=10, nullable=False)
    logo_url: Mapped[Optional[str]] = mapped_column(String(512), nullable=True)

    # Relationships
    workspaces: Mapped[list["Workspace"]] = relationship(
        "Workspace", back_populates="organization", cascade="all, delete-orphan"
    )
    members: Mapped[list["OrgMember"]] = relationship(  # type: ignore[name-defined]
        "OrgMember", back_populates="organization", cascade="all, delete-orphan"
    )
    api_keys: Mapped[list["ApiKey"]] = relationship(
        "ApiKey", back_populates="organization", cascade="all, delete-orphan"
    )
    credentials: Mapped[Optional["OrgCredentials"]] = relationship(
        "OrgCredentials", back_populates="organization", uselist=False, cascade="all, delete-orphan"
    )

    def __repr__(self) -> str:
        return f"<Organization id={self.id} slug={self.slug}>"


class Workspace(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """Logical grouping of scans within an organization."""

    __tablename__ = "workspaces"

    org_id: Mapped[UUID] = mapped_column(
        PGUUID(as_uuid=True), ForeignKey("organizations.id", ondelete="CASCADE"), nullable=False, index=True
    )
    name: Mapped[str] = mapped_column(String(255), nullable=False)
    description: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    is_active: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)

    # Relationships
    organization: Mapped["Organization"] = relationship("Organization", back_populates="workspaces")
    scan_jobs: Mapped[list["ScanJob"]] = relationship(  # type: ignore[name-defined]
        "ScanJob", back_populates="workspace"
    )

    def __repr__(self) -> str:
        return f"<Workspace id={self.id} name={self.name}>"


class ApiKey(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """API key for programmatic access."""

    __tablename__ = "api_keys"

    org_id: Mapped[UUID] = mapped_column(
        PGUUID(as_uuid=True), ForeignKey("organizations.id", ondelete="CASCADE"), nullable=False, index=True
    )
    created_by: Mapped[UUID] = mapped_column(
        PGUUID(as_uuid=True), ForeignKey("users.id", ondelete="SET NULL"), nullable=True
    )
    name: Mapped[str] = mapped_column(String(255), nullable=False)
    key_hash: Mapped[str] = mapped_column(String(64), unique=True, nullable=False, index=True)
    is_active: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)
    last_used: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    expires_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    scopes: Mapped[list[str]] = mapped_column(ARRAY(String), default=list, nullable=False)

    # Relationships
    organization: Mapped["Organization"] = relationship("Organization", back_populates="api_keys")

    def __repr__(self) -> str:
        return f"<ApiKey id={self.id} name={self.name}>"


class InviteCode(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """
    Single-use invite code granting access to register and join an org.
    Generated by org admins/owners; consumed once on registration.
    """

    __tablename__ = "invite_codes"

    org_id: Mapped[UUID] = mapped_column(
        PGUUID(as_uuid=True), ForeignKey("organizations.id", ondelete="CASCADE"), nullable=False, index=True
    )
    created_by: Mapped[UUID] = mapped_column(
        PGUUID(as_uuid=True), ForeignKey("users.id", ondelete="SET NULL"), nullable=True
    )
    code: Mapped[str] = mapped_column(String(32), unique=True, nullable=False, index=True)
    role: Mapped[str] = mapped_column(String(32), default="member", nullable=False)
    email: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)  # optional: restrict to one email
    expires_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    used_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    used_by: Mapped[Optional[UUID]] = mapped_column(
        PGUUID(as_uuid=True), ForeignKey("users.id", ondelete="SET NULL"), nullable=True
    )
    is_revoked: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)

    # Relationships
    organization: Mapped["Organization"] = relationship("Organization", foreign_keys=[org_id])

    @property
    def is_valid(self) -> bool:
        from datetime import timezone as tz
        if self.is_revoked or self.used_at:
            return False
        if self.expires_at and self.expires_at < datetime.now(tz.utc):
            return False
        return True

    def __repr__(self) -> str:
        return f"<InviteCode code={self.code} org_id={self.org_id}>"


class OrgCredentials(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """
    Encrypted third-party API credentials for an organization.
    All *_enc fields store AES-256-GCM Fernet-encrypted values.
    """

    __tablename__ = "org_credentials"

    org_id: Mapped[UUID] = mapped_column(
        PGUUID(as_uuid=True), ForeignKey("organizations.id", ondelete="CASCADE"), unique=True, nullable=False
    )
    shodan_key_enc: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    censys_id_enc: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    censys_secret_enc: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    securitytrails_key_enc: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    github_token_enc: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    alienvault_key_enc: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    passivetotal_user_enc: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    passivetotal_key_enc: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    # Relationships
    organization: Mapped["Organization"] = relationship("Organization", back_populates="credentials")

    def __repr__(self) -> str:
        return f"<OrgCredentials org_id={self.org_id}>"
